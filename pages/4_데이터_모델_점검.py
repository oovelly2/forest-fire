"""데이터 구조·전처리·모델 성능·한계를 보여 주는 점검 화면."""
import pandas as pd
import streamlit as st

import core
from common import get_bundle

st.set_page_config(page_title="데이터·모델 점검", page_icon="🔍", layout="wide")
st.title("🔍 데이터·모델 점검")
b = get_bundle()
W, F = core.load_weather(), core.load_fires()

st.header("1. 데이터 구조")
c1, c2 = st.columns(2)
c1.markdown(f"**기상_산불_일별.csv** — shape {W.shape}, 관측소 5곳 × 731일 (2024-01-01~2025-12-31)")
c1.write(", ".join(W.columns))
c2.markdown(f"**산불_기상_병합.csv** — shape {F.shape}, 산불 1건=1행 (2024-01-24~2025-12-11)")
c2.write(", ".join(F.columns))

st.header("2. 전처리")
wr, fr = b["weather_report"], b["fire_report"]
st.dataframe(pd.DataFrame({"항목": ["중복 행 제거(기상)", "일강수량 빈칸 → 0", "기온 결측 → 앞날 값", "습도 결측 → 앞날 값", "중복 제거(산불)"],
                           "건수": [wr["중복_제거"], wr["강수_빈칸_0처리"], wr["기온_결측"], wr["습도_결측"], fr["중복_제거"]]}),
             hide_index=True)
st.markdown("""
- **강수량 빈칸(2,270행, 62%)**: 값이 있는 날보다 습도가 약 15%p 낮아 '비 안 온 날'로 보이므로 0으로 처리했습니다. 단, 관측 누락이 일부 섞였을 가능성은 배제할 수 없습니다.
- **기온·습도 결측**은 같은 관측소의 *전날* 값으로 채웠습니다(미래 값은 쓰지 않음).
- **용인/용인처인**은 같은 시라 '용인'으로 합쳤습니다 → 26개 지역.
- **2024년 누락 10건 추가**: 산림청 API와 대조해 기존 CSV에 없던 2024년 산불 10건을 두 CSV에 반영했습니다(177 → 187건). 자세한 내용은 README 참고.
- **미발생 처리**: 기상 자료가 모두 있는 2024-01-01~2025-12-31 전체를 수집 범위로 보고, 지역·날짜 조합 19,006개 중 기록 없는 날을 0(미발생)으로 했습니다. 기록이 아예 없는 시군(안양·부천 등 5곳)은 미발생인지 미수집인지 알 수 없어 제외했습니다.
""")

st.header("3. 지역 → 기상 관측소 연결")
st.dataframe(b["region_map"][["지역", "관측소", "거리_km"]], hide_index=True, width="stretch")
st.caption("각 시군을 직선거리가 가장 가까운 관측소 1곳에 연결했습니다(좌표는 data/merge.py의 대략 값). 수원 관측소에 10개 시군이 몰리고 가평·평택·안성은 30km 이상 떨어져 있어 오차가 있을 수 있습니다.")

st.header("4. 달력 변수의 실제 효과")
st.write("주말·공휴일에 산불이 더 많다고 가정하지 않고, 2024~2025년 실제 발생률을 확인했습니다.")
st.dataframe(core.calendar_effect_table(b["features"]), hide_index=True, width="stretch")
st.caption("'월 보정 비율'은 같은 달 평일 발생률로 기대한 발생 수 대비 실제 발생 수입니다(평일=1). "
           "발생 건수가 적어(특히 공휴일) 우연일 수 있으며, 통계적 검정은 하지 않았습니다.")

st.header("5. 모델 성능 비교 (같은 분할·같은 표본·같은 경보 기준)")
m, mp, bl = b["metrics"], b["metrics_prev"], b["baseline"]
st.write(f"학습 {b['train_range'][0]:%Y-%m-%d}~{b['train_range'][1]:%Y-%m-%d} (발생 {b['train_pos']}건) → "
         f"평가 {b['test_range'][0]:%Y-%m-%d}~{b['test_range'][1]:%Y-%m-%d} (발생 {b['test_pos']}건, 표본 {b['test_n']:,}). 시간 순서로 나눴습니다.")
rows = ["ROC-AUC", "PR-AUC", "재현율", "정밀도", "경보_비율", "경보_기준확률", "정확도"]
table = pd.DataFrame({"① 계절만": bl, "② 기존(기상+이력)": mp, "③ 기존+달력 (서비스 사용)": m}).loc[rows]
st.dataframe(table.round(4), width="stretch")
dlo, dhi = m["AUC차이_95%구간"]
d_auc, d_rec = m["ROC-AUC"] - mp["ROC-AUC"], m["재현율"] - mp["재현율"]
hit_extra = round(d_rec * m["양성_수"])
verdict = ("신뢰구간이 0을 포함해 **뚜렷한 개선이라고 말할 수 없습니다**" if dlo <= 0 <= dhi
           else ("개선됐습니다" if d_auc > 0 else "오히려 나빠졌습니다"))
st.markdown(f"""
- 경보 기준은 모든 모델이 같은 방법입니다: **학습기간 예측 확률의 상위 10% 지점**. ③의 실제 임계값은 {m['경보_기준확률']:.2%}, ②는 {mp['경보_기준확률']:.2%}입니다. 평가 데이터로 바꾸지 않았습니다.
- ②→③ ROC-AUC 변화 {d_auc:+.4f} (②와의 차이 95% 구간 {dlo:+.3f}~{dhi:+.3f}) → {verdict}.
- 재현율 변화 {d_rec:+.3f} (발생 {m['양성_수']}건 중 약 {hit_extra:+d}건), 정밀도 {m['정밀도'] - mp['정밀도']:+.4f}. 이 정도 차이는 우연으로도 생길 수 있습니다.
- 달력 변수는 모델에 포함돼 있지만 성능을 눈에 띄게 높이지는 않았습니다. 서비스 모델은 요청대로 ③을 사용하지만, ②와 사실상 비슷한 수준입니다.
- **정확도는 의미가 작습니다.** 전부 '미발생'이라 해도 {m['항상_미발생_정확도']:.1%}가 나옵니다. 정밀도는 약 {m['정밀도']:.0%}, 재현율은 약 {m['재현율']:.0%}라서 **'확률이 높은 지역을 먼저 본다'는 우선순위 용도**로만 해석해야 합니다.
""")
_hist = b["panel"][b["panel"]["일시"] <= core.PERIOD_END]
POS, RATE = int(_hist["산불발생"].sum()), _hist["산불발생"].mean()
st.header("6. 한계")
st.markdown(f"""
- 학습 자료가 2년뿐이고 산불 발생 지역일이 {POS}일({RATE:.1%})이라 모델이 불안정합니다. 평가 구간도 한 해(2025)뿐입니다.
- 산불 원인의 상당수는 사람 활동(담뱃불·쓰레기 소각 등)이라 기상만으로는 설명되지 않습니다.
- **달력 변수(요일·주말·공휴일)는 사람 활동의 간접 지표일 뿐, 실제 입산·소각 활동을 측정한 값이 아닙니다.** 이번 평가에서 성능 향상도 뚜렷하지 않았습니다.
- 원인이 '미상'이거나 '기타'인 산불이 {core.unknown_cause_summary(b['fires'])['합계_비율']:.0%}라 원인 기반 분석에도 한계가 있습니다. 원인 정보는 발생 후 기록이므로 예측에는 쓰지 않았습니다.
- 지역별 기상은 5개 관측소로 근사했고, 임야 면적·지형·인구 등 노출 요인은 반영하지 못했습니다.
- 산불 기록 날짜가 1월 24일부터 시작해 1월 초 미발생 처리가 맞는지 확인하지 못했습니다.
- **2026년 산불 기록(API)**은 이력 조회와 '최근 90일 산불 건수'에만 쓰고 학습·평가에는 쓰지 않았습니다. 원인은 기존 표기로 바꾼 값('건축물화재비화'→'건축물 실화' 등은 근사)이며 '원인 미상'은 API에 없어 '기타'에 포함됩니다. 2026년에 처음 나온 광명·부천은 과거 이력이 없어 예측 대상에서 제외했습니다.
- 예측에 쓰는 '전날 기상'은 실제 관측값이며 기상예보가 아닙니다. 예보 연동은 향후 과제입니다.
""")
